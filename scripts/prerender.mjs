import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const distDir = path.resolve(rootDir, 'dist');
const distServerDir = path.resolve(rootDir, 'dist-server');
const distServerEntry = path.resolve(distServerDir, 'entry-server.js');

// Imagens de compartilhamento (WhatsApp/Facebook): JPG leve, 1,91:1, gerado em public/og/
// WhatsApp não exibe prévia de imagens pesadas (> ~300 KB) e tem suporte irregular a WebP.
const OG_IMAGES = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'og-images.json'), 'utf-8'));
const OG_DEFAULT_SRC = 'capa-site-quero-meu-mcmv-open-graph.webp';

function resolveOgImage(route, domain) {
  const src = route.development && route.development.image
    ? String(route.development.image).split('/').pop()
    : OG_DEFAULT_SRC;
  const og = OG_IMAGES[src] || OG_IMAGES[OG_DEFAULT_SRC];
  return { url: `${domain}/${og.file}`, width: og.width, height: og.height };
}

function escapeAttr(str) {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function escapeText(str) {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * Replaces an existing tag matching regex or inserts before </head> if not present.
 * Uses a replacement function to prevent '$' characters in newTag from triggering special replacements.
 */
function replaceOrInsertHeadTag(html, regex, newTag) {
  if (regex.test(html)) {
    return html.replace(regex, () => newTag);
  }
  return html.replace(/<\/head>/i, () => `  ${newTag}\n</head>`);
}

async function runPrerender() {
  console.log('[Prerender] Starting build-time static rendering (SSG)...');

  if (!fs.existsSync(distServerEntry)) {
    throw new Error(
      `Server entry file not found at ${distServerEntry}. Run 'vite build --ssr src/entry-server.tsx --outDir dist-server' first.`
    );
  }

  const templateHtmlPath = path.join(distDir, 'index.html');
  if (!fs.existsSync(templateHtmlPath)) {
    throw new Error(`Template index.html not found at ${templateHtmlPath}. Run 'vite build' first.`);
  }

  // 1. Read the template generated by vite build EXACTLY ONCE into memory before writing any files
  const rawTemplate = fs.readFileSync(templateHtmlPath, 'utf-8');

  // Load compiled server bundle
  const { render, ROUTES, buildSchemaGraph, CANONICAL_DOMAIN } = await import(
    pathToFileURL(distServerEntry).href
  );

  console.log(`[Prerender] Found ${ROUTES.length} routes to process.`);

  // 2. Process non-root routes first, and route "/" STRICTLY LAST
  const nonRootRoutes = ROUTES.filter((r) => r.path !== '/');
  const rootRoute = ROUTES.find((r) => r.path === '/');
  const orderedRoutes = [...nonRootRoutes, ...(rootRoute ? [rootRoute] : [])];

  for (const route of orderedRoutes) {
    const isRoot = route.path === '/';
    const canonicalUrl = isRoot ? `${CANONICAL_DOMAIN}/` : `${CANONICAL_DOMAIN}${route.path}`;

    // Target file path (no trailing slashes, ex: dist/sobre.html and dist/index.html for /)
    const targetFile = route.outputFile
      ? path.join(distDir, route.outputFile)
      : isRoot
      ? path.join(distDir, 'index.html')
      : path.join(distDir, `${route.path.replace(/^\//, '')}.html`);

    console.log(`[Prerender] Rendering route: ${route.path} -> ${path.relative(rootDir, targetFile)}`);

    // Render application React tree
    const { html: appHtml } = render(route.path);

    // Strip hoisted head tags from appHtml and remove static opacity:0 inline styles from motion
    const cleanedAppHtml = appHtml
      .replace(/<title[^>]*>[\s\S]*?<\/title>/gi, '')
      .replace(/<meta[^>]*>/gi, '')
      .replace(/<link[^>]*>/gi, '')
      .replace(/<script[^>]*type=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>/gi, '')
      .replace(/style="[^"]*opacity:\s*0[^"]*"/g, (match) => {
        return match
          .replace(/opacity:\s*0;?/g, '')
          .replace(/transform:[^;"]*;?/g, '')
          .replace(/style="\s*"/, '');
      });

    // Start with a clean copy of the in-memory rawTemplate
    let pageHtml = rawTemplate;

    // Clean existing robots and JSON-LD tags
    pageHtml = pageHtml.replace(/<meta(?=[^>]*\bname\s*=\s*["']robots["'])[^>]*\/?>/gi, '');
    pageHtml = pageHtml.replace(/<script[^>]*type=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>/gi, '');

    // Replace or insert head tags with tolerant regexes
    // 1. <title>
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<title[^>]*>[\s\S]*?<\/title>/i,
      `<title>${escapeText(route.title)}</title>`
    );

    // 2. <meta name="description">
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bname\s*=\s*["']description["'])[^>]*\/?>/i,
      `<meta name="description" content="${escapeAttr(route.description)}" />`
    );

    // 3. <link rel="canonical">
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<link(?=[^>]*\brel\s*=\s*["']canonical["'])[^>]*\/?>/i,
      `<link rel="canonical" href="${canonicalUrl}" />`
    );

    // 4. <meta property="og:title">
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:title["'])[^>]*\/?>/i,
      `<meta property="og:title" content="${escapeAttr(route.title)}" />`
    );

    // 5. <meta property="og:description">
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:description["'])[^>]*\/?>/i,
      `<meta property="og:description" content="${escapeAttr(route.description)}" />`
    );

    // 6. <meta property="og:url">
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:url["'])[^>]*\/?>/i,
      `<meta property="og:url" content="${canonicalUrl}" />`
    );

    // Additional Open Graph & Twitter metadata
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:type["'])[^>]*\/?>/i,
      `<meta property="og:type" content="${route.schemaType === 'Article' ? 'article' : 'website'}" />`
    );

    const ogImg = resolveOgImage(route, CANONICAL_DOMAIN);
    // Remove variações antigas de og:image:* antes de reinserir
    pageHtml = pageHtml.replace(/<meta(?=[^>]*\bproperty\s*=\s*["']og:image:[a-z_]+["'])[^>]*\/?>\s*/gi, '');
    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:image["'])[^>]*\/?>/i,
      `<meta property="og:image" content="${ogImg.url}" />\n` +
      `    <meta property="og:image:secure_url" content="${ogImg.url}" />\n` +
      `    <meta property="og:image:type" content="image/jpeg" />\n` +
      `    <meta property="og:image:width" content="${ogImg.width}" />\n` +
      `    <meta property="og:image:height" content="${ogImg.height}" />\n` +
      `    <meta property="og:image:alt" content="${escapeAttr(route.title)}" />`
    );

    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:site_name["'])[^>]*\/?>/i,
      `<meta property="og:site_name" content="Quero Meu MCMV" />`
    );

    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bproperty\s*=\s*["']og:locale["'])[^>]*\/?>/i,
      `<meta property="og:locale" content="pt_BR" />`
    );

    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bname\s*=\s*["']twitter:card["'])[^>]*\/?>/i,
      `<meta name="twitter:card" content="summary_large_image" />`
    );

    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bname\s*=\s*["']twitter:title["'])[^>]*\/?>/i,
      `<meta name="twitter:title" content="${escapeAttr(route.title)}" />`
    );

    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bname\s*=\s*["']twitter:description["'])[^>]*\/?>/i,
      `<meta name="twitter:description" content="${escapeAttr(route.description)}" />`
    );

    pageHtml = replaceOrInsertHeadTag(
      pageHtml,
      /<meta(?=[^>]*\bname\s*=\s*["']twitter:image["'])[^>]*\/?>/i,
      `<meta name="twitter:image" content="${ogImg.url}" />`
    );

    // Robots meta tag
    if (route.noindex) {
      const robotsContent = route.nofollow ? 'noindex, nofollow' : 'noindex';
      pageHtml = pageHtml.replace(
        /<\/head>/i,
        () => `  <meta name="robots" content="${robotsContent}" />\n</head>`
      );
    }

    // JSON-LD Schema.org block
    if (!route.noindex) {
      const jsonLdContent = JSON.stringify(buildSchemaGraph(route));
      pageHtml = pageHtml.replace(
        /<\/head>/i,
        () => `  <script type="application/ld+json">${jsonLdContent}</script>\n</head>`
      );
    }

    // Inject rendered React HTML into <div id="root">
    // Tolerant regex handling spaces, newlines, and any extra attributes on <div id="root">
    const rootDivRegex = /<div\s+[^>]*\bid=["']root["'][^>]*>[\s\S]*?<\/div>/i;
    if (!rootDivRegex.test(pageHtml)) {
      throw new Error(`[Prerender] Target <div id="root"> not found in template for route ${route.path}`);
    }

    // Use callback function to avoid special $ pattern expansion in cleanedAppHtml
    pageHtml = pageHtml.replace(rootDivRegex, () => `<div id="root">${cleanedAppHtml}</div>`);

    // Ensure directory exists and write target file
    const targetDir = path.dirname(targetFile);
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    fs.writeFileSync(targetFile, pageHtml, 'utf-8');
  }

  // 3. Build sitemap.xml
  console.log('[Prerender] Generating sitemap.xml...');
  const indexableRoutes = ROUTES.filter((r) => !r.noindex && r.path !== '/404');
  console.log(`[Prerender] Found ${indexableRoutes.length} indexable routes for sitemap.`);

  const today = new Date().toISOString().split('T')[0];
  let sitemapXml = '<?xml version="1.0" encoding="UTF-8"?>\n';
  sitemapXml += '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n';

  for (const route of indexableRoutes) {
    const loc = route.path === '/' ? `${CANONICAL_DOMAIN}/` : `${CANONICAL_DOMAIN}${route.path}`;
    const priority = route.priority || (route.path === '/' ? '1.0' : '0.8');
    const changefreq = route.changefreq || 'weekly';

    sitemapXml += '  <url>\n';
    sitemapXml += `    <loc>${loc}</loc>\n`;
    sitemapXml += `    <lastmod>${today}</lastmod>\n`;
    sitemapXml += `    <changefreq>${changefreq}</changefreq>\n`;
    sitemapXml += `    <priority>${priority}</priority>\n`;
    sitemapXml += '  </url>\n';
  }
  sitemapXml += '</urlset>\n';

  fs.writeFileSync(path.join(distDir, 'sitemap.xml'), sitemapXml, 'utf-8');

  // Copy llms.txt, robots.txt, and _headers to dist
  const publicDir = path.join(rootDir, 'public');
  for (const fileName of ['llms.txt', 'robots.txt', '_headers']) {
    const src = path.join(publicDir, fileName);
    const dest = path.join(distDir, fileName);
    if (fs.existsSync(src)) {
      fs.copyFileSync(src, dest);
    }
  }

  // 4. Validate all generated files
  console.log('[Prerender] Validating all generated HTML files...');
  let validationErrors = 0;

  for (const route of ROUTES) {
    const isRoot = route.path === '/';
    const targetFile = route.outputFile
      ? path.join(distDir, route.outputFile)
      : isRoot
      ? path.join(distDir, 'index.html')
      : path.join(distDir, `${route.path.replace(/^\//, '')}.html`);

    if (!fs.existsSync(targetFile)) {
      console.error(`[Prerender][VALIDATION ERROR] File does not exist: ${targetFile}`);
      validationErrors++;
      continue;
    }

    const content = fs.readFileSync(targetFile, 'utf-8');

    // Title validation
    const titleMatch = content.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
    const actualTitle = titleMatch ? titleMatch[1].trim() : '';
    const expectedTitle = route.title.trim();

    if (!actualTitle || actualTitle !== expectedTitle) {
      console.error(
        `[Prerender][VALIDATION ERROR] Title mismatch in ${path.relative(rootDir, targetFile)}:\n` +
        `  Expected: "${expectedTitle}"\n` +
        `  Actual:   "${actualTitle}"`
      );
      validationErrors++;
    }

    // Root div validation (must have substantial non-empty content)
    const rootMatch = content.match(/<div\s+[^>]*\bid=["']root["'][^>]*>([\s\S]*?)<\/div>/i);
    const rootInner = rootMatch ? rootMatch[1].trim() : '';
    if (!rootInner || rootInner.length < 50) {
      console.error(
        `[Prerender][VALIDATION ERROR] <div id="root"> is empty or too short (${rootInner.length} chars) in ${path.relative(rootDir, targetFile)}`
      );
      validationErrors++;
    }

    // Strict validation specifically for dist/index.html (Home)
    if (isRoot) {
      if (!content.includes('Saia do aluguel! Seu apartamento')) {
        console.error('[Prerender][VALIDATION ERROR] Expected H1 copy not found in dist/index.html');
        validationErrors++;
      }

      if (!content.includes('application/ld+json')) {
        console.error('[Prerender][VALIDATION ERROR] JSON-LD script not found in dist/index.html');
        validationErrors++;
      }
    }
  }

  if (validationErrors > 0) {
    console.error(`[Prerender] Validation failed with ${validationErrors} error(s)! Aborting build.`);
    process.exit(1);
  }

  console.log('[Prerender] All generated HTML files passed validation successfully!');

  // 5. Clean up temporary dist-server directory
  try {
    if (fs.existsSync(distServerDir)) {
      fs.rmSync(distServerDir, { recursive: true, force: true });
      console.log('[Prerender] Cleaned up dist-server.');
    }
  } catch (err) {
    console.warn('[Prerender] Warning while cleaning dist-server:', err.message);
  }

  console.log('[Prerender] Prerendering finished successfully!');
}

runPrerender().catch((err) => {
  console.error('[Prerender] FATAL ERROR:', err);
  process.exit(1);
});
